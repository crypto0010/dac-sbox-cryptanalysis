"""Frozen 5-bit S-box tables of the DAC study, with their provenance.

Every table is a permutation of ``0 .. 31`` stored as a list of Python ints
(``table[x] = S(x)``), accompanied by its inverse (``*_INV``) and a
:class:`FrozenSBox` record in :data:`TABLES`.  The tables produced by
:func:`src.sbox_optimizer.optimize_dac_sbox` are frozen here together with
the seed and iteration count that generated them; :func:`regenerate` reruns
the search and checks that the stored constant is reproduced bit for bit.

``DAC_SBOX_REF``
    The original DAC S-box, Table 3 of Sarmila & Manisekaran (EIJ 2025),
    copied verbatim from :data:`src.sbox.DAC_SBOX` for reference.
    NL(S) 8 (coordinates [8, 10, 10, 8, 10]), differential uniformity 8,
    max LAT bias 8, SAC 0.515 in [0.25, 0.75], BIC-SAC 0.5175, boomerang
    uniformity 14, all 31 components balanced and of degree 4.
``EDAC_SBOX``
    The "Enhanced DAC" table printed in ``paper.tex`` (Table
    ``tab:edac_sbox``).  It came from the legacy, unseeded swap-based
    simulated annealing and therefore cannot be regenerated.  Its coordinate
    nonlinearities are all 10, but six of the 31 components have
    nonlinearity 8, so the true NL(S) is 8 (max LAT bias 8, LAP 0.25); the
    differential uniformity is 4, SAC 0.53 in [0.375, 0.75], BIC-SAC 0.5125,
    boomerang uniformity 16, degree 4 throughout.
``DAC_OPT_SBOX``
    ``optimize_dac_sbox("affine_inverse", seed=0.5, iterations=4096)``:
    ``S(x) = A * INV(B * x ^ b) ^ a`` with ``INV(x) = x^-1`` in
    GF(2^5) = F_2[x] / (x^5 + x^2 + 1), ``A`` rows (MSB first)
    ``[4, 11, 13, 14, 18]``, ``a = 4``, ``B`` rows ``[21, 9, 29, 22, 14]``,
    ``b = 29``.  Differential uniformity 2 (APN), NL(S) 10 (every component),
    max LAT bias 6 (LAP 0.1875), every SAC entry exactly 0.5, BIC-SAC 0.5075
    in [0.45, 0.55], BIC-NL 10, boomerang uniformity 2, all 31 components
    balanced and of the maximal degree 4.  The exhaustive enumeration
    :func:`src.sbox_optimizer.enumerate_input_bases` shows that this is the
    best SAC / BIC-SAC combination of the whole inversion class, and the
    chaos-driven search reaches it for every seed tried (50 seeds in
    (0, 1/2]); the paper's key seed 0.5 is therefore used.
``DAC_OPT_GOLD_SBOX``
    ``optimize_dac_sbox("affine_gold", seed=0.5, iterations=512)``: the same
    construction on the Gold map ``x^3`` with ``A`` rows ``[1, 2, 4, 8, 16]``,
    ``a = 1``, ``B`` rows ``[21, 5, 19, 11, 12]``, ``b = 1``.  Almost bent:
    differential uniformity 2, NL(S) 12, max LAT bias 4 (LAP 0.125), SAC and
    BIC-SAC exactly 0.5 everywhere, BIC-NL 12, boomerang uniformity 2, but
    algebraic degree 2 for every component.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Sequence

from .sbox_optimizer import optimize_dac_sbox

DAC_SBOX_REF: List[int] = [
    30, 24,  9, 27, 28, 26,  4, 22,  2, 15, 29,  5, 13,  8, 25,  3,
    11, 10, 16, 31,  0, 20, 14, 21,  1, 12, 18,  6, 23, 19, 17,  7,
]

EDAC_SBOX: List[int] = [
    27, 10, 31,  5, 14,  6, 24, 26, 13, 18, 30,  8, 20, 25, 22,  2,
    19,  1, 16, 21, 15, 28, 29,  4,  7, 11, 17, 12,  3,  0,  9, 23,
]

DAC_OPT_SEED = 0.5
DAC_OPT_ITERATIONS = 4096
DAC_OPT_SBOX: List[int] = [
     2,  8, 19, 14,  7, 10, 18,  0, 13, 21, 17, 16, 28, 26,  6,  9,
     5, 30, 24, 22,  3,  4, 12, 29, 23, 31, 20,  1, 11, 27, 15, 25,
]

DAC_OPT_GOLD_SEED = 0.5
DAC_OPT_GOLD_ITERATIONS = 512
DAC_OPT_GOLD_SBOX: List[int] = [
    17, 22,  5,  6,  9, 28, 16,  1,  3, 23, 11, 27, 24, 30, 29, 31,
     0, 13,  7, 14, 19, 12, 25,  2, 20, 10, 15, 21,  4,  8, 18, 26,
]


def inverse_table(table: Sequence[int]) -> List[int]:
    """Inverse of a permutation ``table[x] = y`` as a list ``inv[y] = x``."""
    values = [int(v) for v in table]
    if sorted(values) != list(range(len(values))):
        raise ValueError("table is not a permutation of 0 .. len - 1")
    inverse = [0] * len(values)
    for x, y in enumerate(values):
        inverse[y] = x
    return inverse


DAC_SBOX_REF_INV: List[int] = inverse_table(DAC_SBOX_REF)
EDAC_SBOX_INV: List[int] = inverse_table(EDAC_SBOX)
DAC_OPT_SBOX_INV: List[int] = inverse_table(DAC_OPT_SBOX)
DAC_OPT_GOLD_SBOX_INV: List[int] = inverse_table(DAC_OPT_GOLD_SBOX)


@dataclass(frozen=True)
class FrozenSBox:
    """A frozen table and the search that produced it (``strategy`` is
    ``None`` for tables that were not generated by this code base)."""

    name: str
    table: List[int]
    inverse: List[int]
    description: str
    strategy: Optional[str] = None
    seed: Optional[float] = None
    iterations: Optional[int] = None


TABLES: Dict[str, FrozenSBox] = {
    "DAC": FrozenSBox(
        "DAC", DAC_SBOX_REF, DAC_SBOX_REF_INV,
        "original DAC S-box, paper Table 3 (Sarmila & Manisekaran, EIJ 2025)"),
    "E-DAC": FrozenSBox(
        "E-DAC", EDAC_SBOX, EDAC_SBOX_INV,
        "table printed in paper.tex (tab:edac_sbox); legacy unseeded annealing, "
        "not reproducible; true NL(S) = 8"),
    "DAC-OPT": FrozenSBox(
        "DAC-OPT", DAC_OPT_SBOX, DAC_OPT_SBOX_INV,
        "affine equivalent of x^-1 over GF(2^5): DU 2, NL 10, degree 4, SAC 0.5",
        "affine_inverse", DAC_OPT_SEED, DAC_OPT_ITERATIONS),
    "DAC-OPT-GOLD": FrozenSBox(
        "DAC-OPT-GOLD", DAC_OPT_GOLD_SBOX, DAC_OPT_GOLD_SBOX_INV,
        "affine equivalent of x^3 over GF(2^5): DU 2, NL 12, degree 2, SAC 0.5",
        "affine_gold", DAC_OPT_GOLD_SEED, DAC_OPT_GOLD_ITERATIONS),
}


def regenerate(name: str, check: bool = True) -> Dict[str, Any]:
    """Rerun the search that produced the frozen table ``name``.

    Returns the :func:`~src.sbox_optimizer.optimize_dac_sbox` result (keys
    ``sbox``, ``metrics``, ``objective``, ``provenance``).  With ``check``
    (the default) a ``RuntimeError`` is raised if the regenerated table is
    not identical to the stored constant, so the call doubles as a
    reproducibility test.  Raises ``KeyError`` for an unknown name and
    ``ValueError`` for a table that has no stored search (``DAC``, ``E-DAC``).
    """
    record = TABLES[name]
    if record.strategy is None:
        raise ValueError(f"{name!r} is a static table and has no search to rerun")
    result = optimize_dac_sbox(record.strategy, seed=record.seed,
                               iterations=record.iterations)
    if check and result["sbox"] != record.table:
        raise RuntimeError(
            f"{name!r} was not reproduced: {record.strategy} with seed "
            f"{record.seed} gave {result['sbox']} instead of {record.table}")
    return result


def regenerable_tables() -> List[str]:
    """Names of the tables in :data:`TABLES` that :func:`regenerate` can rerun."""
    return [name for name, record in TABLES.items() if record.strategy is not None]
